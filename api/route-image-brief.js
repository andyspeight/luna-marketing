// Image Lab — smart router
//
// Tiny Claude-powered classifier. Takes a free-text image brief, returns one
// of: photoreal | mockup | text | vector. Used by Image Lab's "Auto-detect"
// option so the user doesn't have to choose a category manually.
//
// Cost per call: ~$0.001 with Haiku 4.5. Negligible.
//
// Required env vars:
//   ANTHROPIC_API_KEY          — server-only, never client-side
//   UPSTASH_REDIS_REST_URL     — shared with replicate-generate.js
//   UPSTASH_REDIS_REST_TOKEN   — shared with replicate-generate.js
// ============================================================================

import Anthropic from '@anthropic-ai/sdk';
import { Ratelimit } from '@upstash/ratelimit';
import { Redis } from '@upstash/redis';

// ---------------------------------------------------------------------------
// Owner-session auth helper — see replicate-generate.js for full notes.
