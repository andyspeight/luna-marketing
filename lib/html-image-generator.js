// lib/html-image-generator.js
//
// Generates marketing images by sending HTML/CSS to the HCTI API
// (htmlcsstoimage.com), which renders it in real Google Chrome and
// returns a PNG.
//
// Why HCTI vs SVG-via-Claude or FLUX:
//   SVG generation hits a quality ceiling because Claude has to
//   hand-position every element with no rendering loop. FLUX is great
//   for photography but cannot produce information design with real
//   charts, real typography, real layout.
//
//   HCTI renders HTML in actual Chrome. Same engine as every modern
//   website. CSS handles layout (flexbox, grid). Google Fonts load
//   server-side. Backdrop filters, gradients, shadows all work natively.
//   1-3 second render. Pixel-perfect.
//
// Pipeline:
//   1. Caller provides HTML (already generated by Claude)
//   2. POST to HCTI with viewport + device_scale params
//   3. HCTI returns a permanent CDN URL
//   4. Download the PNG and re-host to our Blob (stable URL, scoped to tenant)
//   5. Return our Blob URL + metadata
//
// We re-host because HCTI URLs work forever for paid accounts but we want
// images served from our own infrastructure for consistency, control,
// and to avoid third-party CDN dependence in saved email drafts.
//
// Author: Travelgenix
// Date:   18 May 2026

const { put } = require("@vercel/blob");

const HCTI_USER_ID = process.env.HCTI_USER_ID;
const HCTI_API_KEY = process.env.HCTI_API_KEY;
const BLOB_TOKEN = process.env.BLOB_READ_WRITE_TOKEN;

const HCTI_ENDPOINT = "https://hcti.io/v1/image";

// Sensible defaults for marketing imagery. Email hero images render at
// 1200x800 logical pixels, 2x device scale = 2400x1600 actual PNG.
const DEFAULT_VIEWPORT_WIDTH = 1200;
const DEFAULT_VIEWPORT_HEIGHT = 800;
const DEFAULT_DEVICE_SCALE = 2;

// HCTI accepts HTML up to 50MB and times out after 30s. We're generally
// well under both, but capping defensively.
const MAX_HTML_BYTES = 1_500_000; // 1.5 MB — plenty for any reasonable design

// ─────────────────────────────────────────────────────────────────────
// CALL HCTI
// ─────────────────────────────────────────────────────────────────────

/**
 * Send HTML to HCTI, get back a PNG URL.
 *
 * @param {Object} opts
 * @param {string} opts.html     Full HTML document or fragment
 * @param {string} [opts.css]    Optional separate CSS (we usually inline)
 * @param {number} [opts.viewport_width]
 * @param {number} [opts.viewport_height]
 * @param {number} [opts.device_scale]  1 = standard, 2 = retina, 3 = ultra
 * @param {string} [opts.selector]      Crop to this CSS selector
 * @param {number} [opts.ms_delay]      Wait N ms after page load before snapshot
 * @returns {Promise<{ok, url, id, error?}>}
 */
async function callHcti(opts) {
  if (!HCTI_USER_ID || !HCTI_API_KEY) {
    return { ok: false, error: "HCTI credentials not configured" };
  }
  if (!opts.html || typeof opts.html !== "string") {
    return { ok: false, error: "html is required" };
  }
  if (opts.html.length > MAX_HTML_BYTES) {
    return { ok: false, error: `html too large (${opts.html.length} bytes, max ${MAX_HTML_BYTES})` };
  }

  const body = {
    html: opts.html,
    viewport_width: opts.viewport_width || DEFAULT_VIEWPORT_WIDTH,
    viewport_height: opts.viewport_height || DEFAULT_VIEWPORT_HEIGHT,
    device_scale: opts.device_scale || DEFAULT_DEVICE_SCALE,
    ms_delay: opts.ms_delay !== undefined ? opts.ms_delay : 500 // give fonts a beat to load
  };
  if (opts.css) body.css = opts.css;
  if (opts.selector) body.selector = opts.selector;

  // HCTI uses HTTP Basic auth: User ID as username, API Key as password
  const auth = Buffer.from(`${HCTI_USER_ID}:${HCTI_API_KEY}`).toString("base64");

  let response;
  try {
    response = await fetch(HCTI_ENDPOINT, {
      method: "POST",
      headers: {
        "Authorization": `Basic ${auth}`,
        "Content-Type": "application/json"
      },
      body: JSON.stringify(body)
    });
  } catch (e) {
    return { ok: false, error: `HCTI fetch failed: ${e.message}` };
  }

  if (!response.ok) {
    let detail = "";
    try {
      const data = await response.json();
      detail = data.message || data.error || JSON.stringify(data).slice(0, 300);
    } catch {
      detail = await response.text().catch(() => "");
    }
    return { ok: false, error: `HCTI returned ${response.status}: ${detail.slice(0, 300)}` };
  }

  const data = await response.json();
  if (!data.url || !data.id) {
    return { ok: false, error: "HCTI response missing url/id" };
  }

  return { ok: true, url: data.url, id: data.id };
}

// ─────────────────────────────────────────────────────────────────────
// DOWNLOAD + RE-HOST
// ─────────────────────────────────────────────────────────────────────

async function downloadImage(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`Download failed: ${res.status}`);
  const ab = await res.arrayBuffer();
  return Buffer.from(ab);
}

async function uploadToBlob(buffer, filename) {
  if (!BLOB_TOKEN) return { url: null, error: "BLOB_READ_WRITE_TOKEN not set" };
  try {
    const blob = await put(filename, buffer, {
      access: "public",
      contentType: "image/png",
      addRandomSuffix: false,
      token: BLOB_TOKEN
    });
    return { url: blob.url, error: null };
  } catch (e) {
    return { url: null, error: `Blob upload failed: ${e.message}` };
  }
}

// ─────────────────────────────────────────────────────────────────────
// MAIN
// ─────────────────────────────────────────────────────────────────────

/**
 * Generate an image from HTML and re-host it to our Blob bucket.
 *
 * @param {Object} input
 * @param {string} input.html
 * @param {string} [input.tenantId]
 * @param {number} [input.viewportWidth]
 * @param {number} [input.viewportHeight]
 * @param {number} [input.deviceScale]
 * @param {string} [input.selector]
 * @param {number} [input.msDelay]
 *
 * @returns {Promise<{ok, pngUrl, hctiUrl, hctiId, width, height, elapsedMs, htmlSize, error?}>}
 */
async function generateHtmlImage(input) {
  if (!input || !input.html) {
    return { ok: false, error: "html is required" };
  }

  const startedAt = Date.now();
  const tenantId = input.tenantId || "shared";
  const viewportWidth = input.viewportWidth || DEFAULT_VIEWPORT_WIDTH;
  const viewportHeight = input.viewportHeight || DEFAULT_VIEWPORT_HEIGHT;
  const deviceScale = input.deviceScale || DEFAULT_DEVICE_SCALE;

  // Step 1: call HCTI
  const hctiResult = await callHcti({
    html: input.html,
    viewport_width: viewportWidth,
    viewport_height: viewportHeight,
    device_scale: deviceScale,
    selector: input.selector,
    ms_delay: input.msDelay
  });

  if (!hctiResult.ok) {
    return { ok: false, error: hctiResult.error, htmlSize: input.html.length };
  }

  // Step 2: download from HCTI's CDN
  let pngBuffer;
  try {
    pngBuffer = await downloadImage(hctiResult.url);
  } catch (e) {
    return {
      ok: false,
      error: `Download failed: ${e.message}`,
      hctiUrl: hctiResult.url,
      hctiId: hctiResult.id
    };
  }

  // Step 3: re-host to our Blob
  const filename = `luna-marketing/${tenantId}/html/${Date.now()}-${Math.random().toString(36).slice(2, 9)}.png`;
  const { url: blobUrl, error: uploadError } = await uploadToBlob(pngBuffer, filename);
  if (!blobUrl) {
    return {
      ok: false,
      error: uploadError,
      hctiUrl: hctiResult.url,
      hctiId: hctiResult.id
    };
  }

  return {
    ok: true,
    pngUrl: blobUrl,
    hctiUrl: hctiResult.url,
    hctiId: hctiResult.id,
    width: viewportWidth * deviceScale,
    height: viewportHeight * deviceScale,
    viewportWidth,
    viewportHeight,
    deviceScale,
    htmlSize: input.html.length,
    elapsedMs: Date.now() - startedAt
  };
}

module.exports = {
  generateHtmlImage,
  _internals: { callHcti, downloadImage, uploadToBlob }
};
